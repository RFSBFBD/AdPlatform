export class BillingFeatureComponent implements OnInit {
  private readonly http = inject(HttpClient);

  readonly isLoading = signal<boolean>(false);
  readonly summary = signal<BillingSummaryDto>({
    total_outstanding_balance: 0,
    invoiced_this_month: 0,
    invoices_count_this_month: 0,
    currency: 'USD',
  });

  readonly accounts = signal<AccountProfileDto[]>([]);
  readonly invoices = signal<InvoiceDto[]>([]);

  ngOnInit(): void {
    this.loadBilling();
  }

  loadBilling(): void {
    this.isLoading.set(true);

    this.http.get<{ summary: BillingSummaryDto; accounts: AccountProfileDto[] }>('/api/v1/billing/summary').subscribe({
      next: (res) => {
        this.isLoading.set(false);
        if (res.summary) {
          this.summary.set(res.summary);
          this.accounts.set(res.accounts || []);
        }
      },
      error: () => {
        this.isLoading.set(false);
      }
    });

    this.http.get<{ data: InvoiceDto[] }>('/api/v1/billing/invoices').subscribe({
      next: (res) => {
        this.invoices.set(res.data || []);
      }
    });
  }
}
