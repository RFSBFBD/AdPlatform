    public function test_ai_upstream_failure_returns_structured_error_and_does_not_consume_tokens(): void
    {
        Http::fake([
            'https://api.openai.com/*' => Http::response([
                'error' => [
                    'message' => 'Incorrect API key provided',
                    'type' => 'invalid_request_error',
                ],
            ], 401),
        ]);

        AiConfig::create([
            'user_id' => $this->user->id,
            'provider' => 'openai',
            'api_key' => 'sk-live-invalid-key-test',
            'model' => 'gpt-4o',
            'is_active' => true,
        ]);

        $response = $this->actingAs($this->user, 'sanctum')
            ->postJson('/api/v1/ai/generate-copy', [
                'platform' => 'meta',
                'product_name' => 'Failed Product',
